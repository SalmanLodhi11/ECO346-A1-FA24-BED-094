import pandas as pd

person = pd.read_csv("pslm_person_subset.csv", low_memory=False)
household = pd.read_csv("pslm_hh_subset.csv", low_memory=False)

print("Person dataset shape:", person.shape)
print("Household dataset shape:", household.shape)

print(person.head())
print(household.head())

# Keep only the household columns needed for our analysis
household_info = household[
    ["hhid", "prov_code", "urban_rural", "hhweight"]
]

# Join person data with household information
data = person.merge(
    household_info,
    on="hhid",
    how="left"
)

# Select rural Balochistan: Variant 6
data = data[
    (data["prov_code"] == 4) &
    (data["urban_rural"] == 1)
].copy()

print("Rows after filtering:", len(data))
print(data[["hhid", "age", "sex", "literate", "hhweight"]].head())

# Select the literacy sample
literacy = data[
    data["age"].between(10, 64) &
    data["literate"].notna() &
    data["sex"].isin([1, 2]) &
    data["hhweight"].notna() &
    (data["hhweight"] > 0)
].copy()

print("Literacy sample size:", len(literacy))
print("\nSex counts:")
print(literacy["sex"].value_counts().sort_index())

print("\nMissing literacy values:", literacy["literate"].isna().sum())

# Define the age-band labels
age_labels = [
    "10-14", "15-19", "20-24", "25-29", "30-34",
    "35-39", "40-44", "45-49", "50-54", "55-59",
    "60-64"
]

# Group ages into five-year bands
literacy["age_band"] = pd.cut(
    literacy["age"],
    bins=list(range(10, 66, 5)),
    right=False,
    labels=age_labels
)

# Calculate the midpoint of each age band
literacy["age_midpoint"] = (
    literacy["age_band"].cat.codes * 5 + 12
)

# Display a few rows
print(literacy[["age", "age_band", "age_midpoint"]].head(10))

# Count people in each age band
print("\nPeople in each age band:")
print(literacy["age_band"].value_counts().sort_index())

# Calculate the weighted literacy rate for each age band and sex

literacy["weighted_literate"] = (
    literacy["literate"] * literacy["hhweight"]
)

table = (
    literacy.groupby(
        ["age_band", "age_midpoint", "sex"],
        observed=True
    )
    .agg(
        n_persons=("literate", "size"),
        literate_weight_sum=("weighted_literate", "sum"),
        total_weight=("hhweight", "sum")
    )
    .reset_index()
)

# Calculate the weighted literacy rate as a percentage
table["weighted_literacy_rate"] = (
    table["literate_weight_sum"] /
    table["total_weight"] * 100
)

# Convert sex codes to readable labels
table["sex_label"] = table["sex"].map({
    1: "Men",
    2: "Women"
})

# Display the results to one decimal place
table["weighted_literacy_rate"] = (
    table["weighted_literacy_rate"].round(1)
)

print(
    table[
        ["age_band", "sex_label", "n_persons",
         "weighted_literacy_rate"]
    ].to_string(index=False)
)

import matplotlib.pyplot as plt

# Create the figure
fig, ax = plt.subplots(figsize=(10, 6))

# Draw a separate line for men and women
for sex_label in ["Men", "Women"]:
    group = table[table["sex_label"] == sex_label]

    ax.plot(
        group["age_midpoint"],
        group["weighted_literacy_rate"],
        marker="o",
        linewidth=2,
        label=sex_label
    )

# Add titles and labels
ax.set_title(
    "Literacy Rates Decline with Age, Especially for Women"
)
ax.set_xlabel("Age band")
ax.set_ylabel("Weighted literacy rate (%)")

# Show the age-band labels
age_midpoints = list(range(12, 63, 5))
age_labels = [
    "10-14", "15-19", "20-24", "25-29", "30-34",
    "35-39", "40-44", "45-49", "50-54", "55-59",
    "60-64"
]
ax.set_xticks(age_midpoints)
ax.set_xticklabels(age_labels, rotation=45)

ax.set_ylim(0, 100)
ax.grid(axis="y", alpha=0.3)
ax.legend(title="Sex")

fig.tight_layout()

# Save the graph as an SVG file
fig.savefig("q5_literacy_by_age_python.svg", format="svg")
plt.show()

